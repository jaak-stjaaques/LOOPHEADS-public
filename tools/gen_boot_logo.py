"""Pack the selected startup artwork into a small RGB565 run-length bitmap."""

from itertools import groupby
from pathlib import Path

from PIL import Image, ImageChops


root = Path(__file__).resolve().parent.parent
image = Image.open(root / "assets/loopheads-boot.png").convert("RGB")
background = Image.new("RGB", image.size, image.getpixel((0, 0)))
left, top, right, bottom = ImageChops.difference(image, background).getbbox()


def rgb565(pixel):
    red, green, blue = pixel
    return ((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)


pixels = map(rgb565, image.crop((left, top, right, bottom)).getdata())
runs = [(sum(1 for _ in group), color) for color, group in groupby(pixels)]
lines = []
for start in range(0, len(runs), 6):
    lines.append("    " + ", ".join(f"{count}, 0x{color:04x}" for count, color in runs[start:start + 6]) + ",")
header = (
    "/* Generated by tools/gen_boot_logo.py from assets/loopheads-boot.png. */\n"
    f"#define BOOT_LOGO_X {left}u\n"
    f"#define BOOT_LOGO_Y {top}u\n"
    f"#define BOOT_LOGO_WIDTH {right - left}u\n"
    f"#define BOOT_LOGO_HEIGHT {bottom - top}u\n"
    "static const uint16_t boot_logo_runs[] = {\n"
    + "\n".join(lines) + "\n};\n"
)
(root / "firmware/gen/loopheads_boot_logo.h").write_text(header)
